import time
from multiprocessing import Process


def writer(filename, data, count):
    """
    Функция writer записывает заданную строку `data` в файл `filename`
    указанное количество раз (`count`).
    Без синхронизации несколько процессов будут записывать одновременно.
    """
    for _ in range(count):
        # Каждый раз открываем файл заново — это повышает вероятность конфликтов при записи
        with open(filename, 'a') as f:
            f.write(data)
        # Очень короткая задержка, чтобы ОС могла переключиться на другой процесс
        time.sleep(0.0001)


if __name__ == '__main__':
    filename = 'shared_file.txt'

    # Очищаем файл перед запуском, чтобы результат был "чистый"
    open(filename, 'w').close()

    # Создаём две разные порции данных
    data_a = 'A' * 100 + '\n'
    data_b = 'B' * 100 + '\n'

    # Создаём два процесса, которые пишут одновременно в один файл
    proc1 = Process(target=writer, args=(filename, data_a, 200))
    proc2 = Process(target=writer, args=(filename, data_b, 200))

    proc1.start()
    proc2.start()

    # Ожидаем завершения обоих процессов
    proc1.join()
    proc2.join()

    print("Запись завершена. Проверьте содержимое shared_file.txt.")


